"""Write a clean, portable requirements-lock.txt from the CURRENT environment.

    python -m Pipeline.make_lock            (run from the project root, inside the working environment)

Why not plain `pip freeze`? In a conda environment it prints `name @ file:///...` build paths that cannot be
installed elsewhere and hide the version number, and it lists every package ever installed (other courses,
tools, GUI libraries). `importlib.metadata` always gives the real version, and we only list what this project
needs: the direct dependencies from requirements.txt plus the packages whose versions are tied to the
TensorFlow / Transformers stack.
"""
from __future__ import annotations
import re
import sys
from datetime import date
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COUPLED = ["keras", "tokenizers", "huggingface-hub", "safetensors"]   # versions tied to tensorflow / transformers


def direct_dependencies() -> list[str]:
    names = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        m = re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", line)
        if m:
            names.append(m.group(0))
    return names


def main() -> None:
    lines = []
    for name in dict.fromkeys(direct_dependencies() + COUPLED):
        try:
            v = version(name)
        except PackageNotFoundError:
            lines.append(f"# {name}: not installed in this environment")
            continue
        lines.append(f"{name}=={v.split('+')[0]}")      # drop local build labels such as torch's '+cpu'
    header = [
        "# EcoSort - exact versions of the packages this project uses (generated by `python -m Pipeline.make_lock`)",
        f"# Python {sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro} | generated {date.today().isoformat()}",
        "# Install CPU-only PyTorch first:  pip install torch --index-url https://download.pytorch.org/whl/cpu",
        "# then:                            pip install -r requirements-lock.txt",
        "",
    ]
    out = ROOT / "requirements-lock.txt"
    out.write_text("\n".join(header + lines) + "\n")
    print(f"Wrote {out} ({len(lines)} packages)")


if __name__ == "__main__":
    main()
